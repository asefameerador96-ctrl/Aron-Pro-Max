package com.aktcl.aron.backend.analytics

import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonPrimitive
import org.dhatim.fastexcel.Workbook
import org.slf4j.LoggerFactory
import java.io.ByteArrayOutputStream
import java.io.OutputStream
import java.util.Base64

/** xlsx and print renderers of one report result. The rows are exactly the rows of the screen (same engine query, same masking). */
object ReportOutputs {
    /**
     * Formula-injection guard (docs/24 s12.3): a text cell that a spreadsheet would read as a formula (leading `=`, `+`, `-`,
     * `@`, tab or CR, also after blanks) is stored with a leading apostrophe-free quote character so it shows as text.
     */
    fun sanitize(s: String): String {
        val first = s.trimStart(' ').firstOrNull() ?: return s
        return if (first == '=' || first == '+' || first == '-' || first == '@' || first == '\t' || first == '\r' || first == '\n') "'$s" else s
    }

    /** Row-at-a-time xlsx writer: the header and the Info sheet are written with the first row and on [close]; rows are never held. */
    class XlsxWriter(out: OutputStream, private val def: ReportDefinition, private val columns: List<ReportColumn>, private val watermark: String) : AutoCloseable {
        private val wb = Workbook(out, "Aron", "1.0")
        private val ws = wb.newWorksheet("Report")
        private var n = 0

        init { columns.forEachIndexed { c, col -> ws.value(0, c, sanitize(col.label_en)) } }

        fun row(row: Map<String, JsonElement>) { n++; columns.forEachIndexed { c, col -> cell(ws, n, c, row[col.key], col.type) } }

        override fun close() {
            val info = wb.newWorksheet("Info")
            info.value(0, 0, sanitize(def.title_en)); info.value(1, 0, sanitize(watermark)); info.value(2, 0, "rows: $n")
            wb.close()
        }
    }

    fun xlsx(out: OutputStream, def: ReportDefinition, columns: List<ReportColumn>, rows: Iterator<Map<String, JsonElement>>, watermark: String): Int {
        var n = 0
        XlsxWriter(out, def, columns, watermark).use { w -> while (rows.hasNext()) { w.row(rows.next()); n++ } }
        return n
    }

    private const val MAX_EXACT = 9_007_199_254_740_992L // 2^53

    internal fun cell(ws: org.dhatim.fastexcel.Worksheet, r: Int, c: Int, v: JsonElement?, type: String) {
        val p = v as? JsonPrimitive
        when {
            v == null || v is JsonNull || p == null -> Unit
            p.isString -> ws.value(r, c, sanitize(p.content))
            p.content == "true" || p.content == "false" -> ws.value(r, c, p.content.toBoolean())
            // An xlsx number is a double: integers up to 2^53 stay numeric; a larger or non-integer value is written as text,
            // never through toDouble (QA-MNY-03: money is never a float).
            type == "integer" || type == "mtk" -> p.content.toLongOrNull()?.takeIf { it in -MAX_EXACT..MAX_EXACT }?.let { ws.value(r, c, it) } ?: ws.value(r, c, p.content)
            else -> ws.value(r, c, p.content.toDouble())
        }
    }

    fun xlsxBytes(def: ReportDefinition, columns: List<ReportColumn>, rows: List<Map<String, JsonElement>>, watermark: String): ByteArray =
        ByteArrayOutputStream().also { xlsx(it, def, columns, rows.iterator(), watermark) }.toByteArray()

    private fun esc(s: String) = buildString { for (ch in s) when (ch) { '&' -> append("&amp;"); '<' -> append("&lt;"); '>' -> append("&gt;"); '"' -> append("&quot;"); '\'' -> append("&#39;"); else -> append(ch) } }

    private val log = LoggerFactory.getLogger("aron.analytics.report")

    /** Classpath location of the report header mark (generated by tools/brand/build_brand_assets.py, D-BRAND-01: never edit by hand). */
    internal const val MARK_RESOURCE = "brand/aron-mark-64.png"
    private const val MARK_MAX_BYTES = 32 * 1024   // the real file is 4.5 KB; anything bigger is not the mark and would bloat every report
    private val PNG_SIGNATURE = byteArrayOf(0x89.toByte(), 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A)

    /**
     * The Aron mark as a `data:` URI for the print header. The web BFF serves the print view under `img-src data:`, so an embedded image is the
     * only kind that can load. Null when the resource is missing, unreadable, not a PNG or too big: a report never fails over its logo, it
     * prints without it (one warning in the log).
     */
    internal fun loadMarkDataUri(resource: String = MARK_RESOURCE, loader: ClassLoader? = ReportOutputs::class.java.classLoader): String? {
        val uri = try {
            loader?.getResourceAsStream(resource)?.use { it.readNBytes(MARK_MAX_BYTES + 1) }
                ?.takeIf { it.size in PNG_SIGNATURE.size..MARK_MAX_BYTES && it.copyOfRange(0, PNG_SIGNATURE.size).contentEquals(PNG_SIGNATURE) }
                ?.let { "data:image/png;base64," + Base64.getEncoder().encodeToString(it) }
        } catch (e: Exception) {
            log.warn("report header mark {} could not be read ({}); reports print without it", resource, e.javaClass.simpleName)
            return null
        }
        if (uri == null) log.warn("report header mark {} is missing or not a small PNG; reports print without it", resource)
        return uri
    }

    /** Read from the classpath once, on the first print render; never at render time after that. */
    internal val reportMark: String? by lazy { loadMarkDataUri() }

    /**
     * Server-rendered print view: A4-friendly table, Bangla title when present, watermark footer. Every value is HTML-escaped.
     * The title carries the Aron [mark] (a `data:` URI, decorative so alt is empty, a fixed 28 css px, on white paper) when there is one; without it the
     * title and the table are exactly as before. Only the print view carries it: the xlsx export stays unbranded.
     */
    fun printHtml(
        def: ReportDefinition, columns: List<ReportColumn>, rows: Iterator<Map<String, JsonElement>>, watermark: String, mark: String? = reportMark,
    ): Pair<String, Int> {
        var n = 0
        val sb = StringBuilder(8192)
        sb.append("<!doctype html><html lang=\"bn\"><head><meta charset=\"utf-8\"><title>").append(esc(def.title_en)).append("</title>")
            .append("<style>body{font-family:'Noto Sans Bengali','Noto Sans',sans-serif;font-size:11px}table{border-collapse:collapse;width:100%}")
            .append("th,td{border:1px solid #888;padding:2px 4px;text-align:left}td.n{text-align:right}th{background:#eee}@page{size:A4 landscape;margin:10mm}")
            .append("img.mark{width:28px;height:28px;vertical-align:middle;margin-right:8px}</style></head><body>")
            .append("<h2>")
        if (mark != null) sb.append("<img class=\"mark\" src=\"").append(esc(mark)).append("\" alt=\"\" width=\"28\" height=\"28\">")
        sb.append(esc(def.title_en)).append(def.title_bn?.let { " / " + esc(it) } ?: "").append("</h2><table><thead><tr>")
        for (c in columns) sb.append("<th>").append(esc(c.label_en)).append("</th>")
        sb.append("</tr></thead><tbody>")
        while (rows.hasNext()) {
            val row = rows.next(); n++
            sb.append("<tr>")
            for (c in columns) {
                val p = row[c.key] as? JsonPrimitive
                val numeric = p != null && !p.isString && p.content != "null" && p.content != "true" && p.content != "false"
                sb.append(if (numeric) "<td class=\"n\">" else "<td>").append(if (p == null || row[c.key] is JsonNull) "" else esc(p.content)).append("</td>")
            }
            sb.append("</tr>")
        }
        sb.append("</tbody></table><p>").append(esc(watermark)).append(" &middot; rows: ").append(n).append("</p></body></html>")
        return sb.toString() to n
    }
}
