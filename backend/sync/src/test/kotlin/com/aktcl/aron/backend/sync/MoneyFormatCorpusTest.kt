import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Money gate (docs/31, F-SYS-051): shared:rules Formats and Money (what the phones print and show, and what the server
 * renders) against the corpus contract/fixtures/money-format-corpus.json, which the web's formatters are checked against
 * in web/tests/money-format-corpus.test.ts. Same 200 milli-taka amounts, same expected strings: if both pass, the phone
 * and the web show the same figure. The corpus is generated by tools/ci/money-format-corpus.py (integer-only oracle).
 *
 * Not covered here: lakh/crore (shared:rules has no compact formatter; the TSO app's TsoDashboards.compact is in an
 * Android module and formats quantities) and the printed memo form (core-printing DocumentBuilder.money: 2 decimals on a
 * whole paisa, else 3, which is Money.formatTaka with a chosen scale, covered by money2/money3 below).
 */
class MoneyFormatCorpusTest {
    private val corpus: JsonObject = Json.parseToJsonElement(
        File(System.getProperty("aron.repoRoot"), "contract/fixtures/money-format-corpus.json").readText(),
    ).jsonObject
    private val amounts = corpus["amounts"]!!.jsonArray.map { it.jsonObject }

    private fun JsonObject.exp(format: String, locale: String): String {
        val e = this["expect"]!!.jsonObject[format]!!
        return if (e is JsonObject) e[locale]!!.jsonPrimitive.content else e.jsonPrimitive.content
    }

    private fun check(name: String, format: String, impl: (Long, UiLocale) -> String) {
        val bad = ArrayList<String>()
        for (a in amounts) for ((loc, key) in listOf(UiLocale.EN to "en", UiLocale.BN to "bn")) {
            val mtk = a["mtk"]!!.jsonPrimitive.long
            val want = a.exp(format, key)
            val got = impl(mtk, loc)
            if (got != want) bad += "$name [$key] $mtk (${a["note"]!!.jsonPrimitive.content}): got \"$got\", corpus \"$want\""
        }
        assertEquals(emptyList(), bad.take(10), "${bad.size} of ${amounts.size * 2} differ")
    }

    @Test
    fun corpusIsTheAgreedSize() {
        assertEquals(200, amounts.size)
        assertEquals("৳", corpus["taka_sign"]!!.jsonPrimitive.content)
        assertEquals(Formats.TAKA_SIGN, corpus["taka_sign"]!!.jsonPrimitive.content, "the sign the apps print")
    }

    /** F-SYS-051 display (SR Home, memo screens, outlet dues, AMO and TSO money): `1,234.50 ৳`, Bengali digits in Bangla. */
    @Test
    fun formatsMoneyMatchesTheCorpus() = check("Formats.money", "money2") { m, l -> Formats.money(m, l) }

    /** The bare amount (memo amount column, sale review moneyBare): Formats.digits(Money.formatTaka(m, 2)). */
    @Test
    fun bareTwoDecimalAmountMatchesTheCorpus() = check("Formats.digits(Money.formatTaka(2))", "amount2") { m, l -> Formats.digits(Money.formatTaka(m, 2), l) }

    /** Exact three decimals (unit prices, line gross on the printed memo when not a whole paisa). */
    @Test
    fun threeDecimalAmountMatchesTheCorpus() = check("Formats.digits(Money.formatTaka(3))", "money3") { m, l -> Formats.digits(Money.formatTaka(m, 3), l) }

    /** The leading-sign variant (memo selector `৳ 84.00`) carries the same amount. */
    @Test
    fun leadingSignVariantCarriesTheSameAmount() = check("Formats.money(LEADING)", "amount2") { m, l ->
        Formats.money(m, l, sign = SignPosition.LEADING).removePrefix(Formats.TAKA_SIGN + " ")
    }

    @Test
    fun plainThreeDecimalsAreTheGroupedFormWithoutSeparators() {
        for (a in amounts) {
            val mtk = a["mtk"]!!.jsonPrimitive.long
            assertEquals(a.exp("plain3", "en"), Money.formatTaka(mtk, 3).replace(",", ""), "$mtk")
            assertTrue(a.exp("plain3", "en").all { it.isDigit() || it == '.' || it == '-' })
        }
    }
}
